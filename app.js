function apiHeaders(extra={}){
  return {
    apikey: CONFIG.supabaseAnonKey || '',
    Authorization: `Bearer ${CONFIG.supabaseAnonKey || ''}`,
    ...extra
  };
}

async function loadSharedData(){
  if(!SHARED_MODE) return;
  try{
    const [fanRes, reactRes] = await Promise.all([
      fetch(`${CONFIG.supabaseUrl}/rest/v1/fan_content?approved=eq.true&select=*&order=created_at.desc`, {headers: apiHeaders()}),
      fetch(`${CONFIG.supabaseUrl}/rest/v1/content_reactions?select=*`, {headers: apiHeaders()})
    ]);
    if(!fanRes.ok) throw new Error(`fan_content ${fanRes.status}`);
    if(!reactRes.ok) throw new Error(`content_reactions ${reactRes.status}`);
    const fanRows = await fanRes.json();
    const reactRows = await reactRes.json();
    state.fanContent = fanRows.map(row => ({
      id: row.id,
      section: row.section,
      platform: row.platform,
      url: row.url,
      title: row.title,
      point: row.point,
      timestamp: row.timestamp_label || '',
      nickname: row.nickname || 'ANONYMOUS',
      thumbnail: row.thumbnail_url || '',
      createdAt: row.created_at
    }));
    state.serverReactions = Object.fromEntries(reactRows.map(r => [r.content_id, {fire:r.fire||0, heart:r.heart||0, eyes:r.eyes||0}]));
  } catch(err){
    console.warn('Shared FAN PICKS unavailable; using local browser mode.', err);
  }
}

async function uploadSharedThumbnail(file, id){
  if(!SHARED_MODE || !file) return '';
  const safeName = String(file.name || 'thumbnail').replace(/[^a-zA-Z0-9._-]/g,'-');
  const path = `${id}-${safeName}`;
  const res = await fetch(`${CONFIG.supabaseUrl}/storage/v1/object/fan-thumbnails/${encodeURIComponent(path)}`, {
    method:'POST',
    headers: apiHeaders({'Content-Type': file.type || 'application/octet-stream', 'x-upsert':'false'}),
    body:file
  });
  if(!res.ok) throw new Error(`thumbnail upload ${res.status}`);
  return `${CONFIG.supabaseUrl}/storage/v1/object/public/fan-thumbnails/${encodeURIComponent(path)}`;
}

async function insertSharedFanContent(item){
  if(!SHARED_MODE) return item;
  const payload = {
    section:item.section,
    platform:item.platform,
    url:item.url,
    title:item.title,
    point:item.point,
    timestamp_label:item.timestamp || null,
    nickname:item.nickname,
    thumbnail_url:item.thumbnail || null,
    approved:true
  };
  const res = await fetch(`${CONFIG.supabaseUrl}/rest/v1/fan_content`, {
    method:'POST',
    headers: apiHeaders({'Content-Type':'application/json','Prefer':'return=representation'}),
    body:JSON.stringify(payload)
  });
  if(!res.ok) throw new Error(`fan content insert ${res.status}`);
  const [row] = await res.json();
  return {
    ...item,
    id:row.id,
    createdAt:row.created_at,
    thumbnail:row.thumbnail_url || item.thumbnail
  };
}

function loadJSON(key, fallback){
  try { return JSON.parse(localStorage.getItem(key)) ?? fallback; }
  catch { return fallback; }
}
function saveJSON(key, value){ localStorage.setItem(key, JSON.stringify(value)); }
function esc(v='') { return String(v).replace(/[&<>"']/g, s => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[s])); }
