async function changeSharedReaction(id, kind, delta){
  const res = await fetch(`${CONFIG.supabaseUrl}/rest/v1/rpc/change_content_reaction`, {
    method:'POST',
    headers: apiHeaders({'Content-Type':'application/json'}),
    body:JSON.stringify({p_content_id:id,p_kind:kind,p_delta:delta})
  });
  if(!res.ok) throw new Error(`reaction ${res.status}`);
  const row = await res.json();
  const data = Array.isArray(row) ? row[0] : row;
  if(data) state.serverReactions[id] = {fire:data.fire||0,heart:data.heart||0,eyes:data.eyes||0};
  return reactionCount(id,kind);
}
function wireReactions(root=document){
  root.querySelectorAll('.reaction').forEach(btn => btn.addEventListener('click', async () => {
    if(btn.disabled) return;
    const wrap = btn.closest('[data-reactions]');
    const id = wrap.dataset.reactions;
    const kind = btn.dataset.reaction;
    const r = reactionState(id);
    const isActive = !!r.active[kind];
    const delta = isActive ? -1 : 1;
    r.active[kind] = !isActive;
    saveJSON(STORAGE_REACTIONS, state.reactions);
    btn.classList.toggle('active', !isActive);
    if(SHARED_MODE){
      btn.disabled = true;
      try{
        const count = await changeSharedReaction(id,kind,delta);
        btn.querySelector('span').textContent = count;
      }catch(err){
        console.warn(err);
        r.active[kind] = isActive;
        saveJSON(STORAGE_REACTIONS, state.reactions);
        btn.classList.toggle('active', isActive);
        showToast('반응 저장에 실패했어요.');
      }finally{ btn.disabled = false; }
    }else{
      r[kind] = Math.max(0, (r[kind] || 0) + delta);
      saveJSON(STORAGE_REACTIONS, state.reactions);
      btn.querySelector('span').textContent = r[kind];
    }
  }));
}
